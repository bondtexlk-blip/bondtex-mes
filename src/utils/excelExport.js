import * as XLSX from 'xlsx';
import { PLANNING_TIME_SLOTS } from '../services/geminiService';

/**
 * Exports an AI-generated production plan to a multi-sheet Microsoft Excel (.xlsx) file
 * with separate dedicated sheets for each individual assigned machine.
 */
export function exportProductionPlanToExcel(plan) {
  if (!plan) return false;

  try {
    const wb = XLSX.utils.book_new();

    // =========================================================================
    // 1. MASTER PLAN SUMMARY SHEET
    // =========================================================================
    const summaryRows = [
      ['BONDTEX MANUFACTURING EXECUTION SYSTEM - AI PRODUCTION SCHEDULE'],
      ['Generated by Gemini AI Planning Engine', '', '', `Generated At: ${new Date().toLocaleString()}`],
      [],
      ['ORDER SPECIFICATIONS', ''],
      ['PO Number', plan.poNumber || 'N/A'],
      ['Colourway', plan.colour || 'N/A'],
      ['Size', plan.size || 'N/A'],
      ['Style', plan.style || 'N/A'],
      ['Total Planned Target (pcs)', plan.targetQty || 0],
      ['Original Order Qty (pcs)', plan.orderQty || 0],
      [],
      ['TIMELINE & CALENDAR ANALYSIS', ''],
      ['Start Date', plan.startDate],
      ['End Date', plan.endDate],
      ['Total Calendar Days', plan.totalCalendarDays],
      ['Total Working Days (Active)', plan.workingDaysCount],
      ['Off Days (Weekends + Holidays)', plan.offDaysCount],
      ['Average Daily Requirement (pcs/day)', plan.averageDailyTarget],
      [],
      ['AI STRATEGIC INSIGHTS & BOTTLENECK ANALYSIS', ''],
      ['Strategic Overview', plan.aiStrategySummary || 'Balanced Line Distribution'],
      ['Bottleneck Risk Level', plan.bottleneckRisk || 'Low'],
      ['Key Risk / Buffer Guidance', plan.bottleneckNotes || 'Observe standard shift buffers'],
      ['Recommended Line Speed', plan.recommendedLineSpeed || 'N/A'],
      ['Shift Buffer Recommendation', plan.shiftBufferRecommendation || 'N/A'],
      [],
      ['DAY-BY-DAY MASTER CAPACITY SCHEDULE (ALL MACHINES COMBINED)'],
    ];

    // Master day headers
    const machineHeaders = (plan.assignedMachines || []).map((m) => `${m.name} (${m.code})`);
    summaryRows.push([
      'Day #',
      'Date',
      'Day of Week',
      'Total Daily Output (pcs)',
      ...machineHeaders,
    ]);

    // Master day data rows
    (plan.scheduleDays || []).forEach((day) => {
      const machineDayTargets = (plan.assignedMachines || []).map((m) => {
        const mPlan = (day.machinePlans || []).find(
          (mp) => mp.machineId === m.id || mp.machineCode === m.code
        );
        return mPlan?.dailyTarget || 0;
      });

      summaryRows.push([
        day.dayNumber,
        day.date,
        day.dayName,
        day.totalDailyTarget,
        ...machineDayTargets,
      ]);
    });

    const summaryWs = XLSX.utils.aoa_to_sheet(summaryRows);
    XLSX.utils.book_append_sheet(wb, summaryWs, 'Master Summary');

    // =========================================================================
    // 2. SEPARATE INDIVIDUAL SHEETS FOR EACH MACHINE
    // =========================================================================
    const machines = plan.assignedMachines || [];
    const usedSheetNames = new Set(['Master Summary']);

    machines.forEach((machine) => {
      // Calculate machine total output across the entire schedule
      const machineTotalOutput = (plan.scheduleDays || []).reduce((sum, day) => {
        const mPlan = (day.machinePlans || []).find(
          (mp) => mp.machineId === machine.id || mp.machineCode === machine.code
        );
        return sum + (mPlan?.dailyTarget || 0);
      }, 0);

      const machineSheetRows = [
        [`BONDTEX MES - ${machine.name.toUpperCase()} (${machine.code}) PRODUCTION SCHEDULE`],
        ['Machine Category', machine.category || 'N/A', '', 'Type', machine.type || 'N/A'],
        ['Assigned Operator', machine.operatorName || 'Floor Worker', '', 'Rated Daily Capacity', `${machine.dailyTargetQty || 3000} pcs/day`],
        ['Planned Order Total (pcs)', machineTotalOutput, '', 'Order PO', `${plan.poNumber} (${plan.colour} - Sz ${plan.size})`],
        [],
        ['HOURLY SHIFT TIME SLOT TARGET BREAKDOWN (pcs per slot per day)'],
        [
          'Day #',
          'Date',
          'Day of Week',
          'Daily Total',
          ...PLANNING_TIME_SLOTS.map((s) => s.label),
          'Verified Sum',
        ],
      ];

      (plan.scheduleDays || []).forEach((day) => {
        const mPlan = (day.machinePlans || []).find(
          (mp) => mp.machineId === machine.id || mp.machineCode === machine.code
        );

        const slotMap = new Map((mPlan?.hourlySlots || []).map((s) => [s.label, s.targetQty]));
        const slotValues = PLANNING_TIME_SLOTS.map((s) => slotMap.get(s.label) || 0);
        const slotSum = slotValues.reduce((a, b) => a + b, 0);

        machineSheetRows.push([
          day.dayNumber,
          day.date,
          day.dayName,
          mPlan?.dailyTarget || 0,
          ...slotValues,
          slotSum,
        ]);
      });

      // Add summary totals row at bottom of sheet
      const totalsRow = [
        'TOTAL',
        '-',
        '-',
        machineTotalOutput,
        ...PLANNING_TIME_SLOTS.map((s) => {
          return (plan.scheduleDays || []).reduce((sum, day) => {
            const mPlan = (day.machinePlans || []).find(
              (mp) => mp.machineId === machine.id || mp.machineCode === machine.code
            );
            const slot = (mPlan?.hourlySlots || []).find((sl) => sl.label === s.label);
            return sum + (slot?.targetQty || 0);
          }, 0);
        }),
        machineTotalOutput,
      ];
      machineSheetRows.push([]);
      machineSheetRows.push(totalsRow);

      const machineWs = XLSX.utils.aoa_to_sheet(machineSheetRows);

      // Excel sheet names must be <= 31 chars and cannot contain: \ / ? * [ ] :
      let safeSheetName = (machine.name || machine.code)
        .replace(/[\\/?*[\]:]/g, '_')
        .slice(0, 31);
      let counter = 1;
      while (usedSheetNames.has(safeSheetName)) {
        safeSheetName = `${safeSheetName.slice(0, 27)}_${counter++}`;
      }
      usedSheetNames.add(safeSheetName);

      XLSX.utils.book_append_sheet(wb, machineWs, safeSheetName);
    });

    // Write file and trigger instant download
    const cleanPo = (plan.poNumber || 'ORDER').replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 30);
    const cleanSize = (plan.size || 'ALL').replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 20);
    const fileName = `Bondtex_AI_Schedule_${cleanPo}_Sz${cleanSize}_${plan.startDate}_to_${plan.endDate}.xlsx`;

    XLSX.writeFile(wb, fileName);
    return true;
  } catch (err) {
    console.error('Failed to export Excel schedule:', err);
    return false;
  }
}
